"""Run only inside the disposable Debian disk VM; never target host disks."""
import hashlib
import http.server
import functools
import itertools
import json
import os
from pathlib import Path
import signal
import subprocess
import tempfile
import threading
import time

BIN = '/usr/local/bin/aria_move'
ROOTS = [Path('/mnt') / name for name in ('ext4', 'xfs', 'btrfs', 'smb')]
RESULTS = Path('/results')
RESULTS.mkdir()
REPORT = []


def record(stage, **details):
    row = dict(stage=stage, **details)
    REPORT.append(row)
    print(json.dumps(row), flush=True)
    (RESULTS / 'report.json').write_text(json.dumps(REPORT, indent=2))


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def payload(path, size, salt):
    path.parent.mkdir(parents=True, exist_ok=True)
    block = bytes((i + salt) % 251 for i in range(65536))
    with path.open('wb') as stream:
        remaining = size
        while remaining:
            part = block[:min(remaining, len(block))]
            stream.write(part)
            remaining -= len(part)
        stream.flush()
        os.fsync(stream.fileno())
    return digest(path)


def config(incoming, completed, label):
    # Paths are generated by this harness and contain no XML special characters.
    path = RESULTS / (label + '.xml')
    path.write_text(f'<config><download_base>{incoming}</download_base>'
                    f'<completed_base>{completed}</completed_base>'
                    f'<log_level>verbose</log_level><log_file>{RESULTS / (label + ".log")}'
                    '</log_file></config>')
    return path


def launch(cfg, source, count, label):
    output = (RESULTS / (label + '-process.log')).open('wb')
    try:
        return subprocess.Popen([BIN, '--config', str(cfg), label, str(count), str(source)],
                                stdout=output, stderr=subprocess.STDOUT)
    finally:
        output.close()


def wait_all(children, seconds=90):
    deadline = time.monotonic() + seconds
    try:
        while any(child.poll() is None for child in children):
            assert time.monotonic() < deadline, 'hook processes timed out'
            time.sleep(.01)
        assert all(child.returncode == 0 for child in children), [c.returncode for c in children]
    finally:
        for child in children:
            if child.poll() is None:
                child.kill()
            child.wait()


def batch(src_root, dst_root):
    label = f'{src_root.name}-to-{dst_root.name}'
    with tempfile.TemporaryDirectory(prefix='incoming-', dir=src_root) as src, \
            tempfile.TemporaryDirectory(prefix='completed-', dir=dst_root) as dst:
        incoming, completed = Path(src), Path(dst)
        cfg = config(incoming, completed, label)
        jobs, expected = [], {}
        sizes = [0, 1, 4095, 65537, 1048575, 1048576, 1048577, 8388731]
        # Finish writing and close every file before invoking any hook.
        for index, size in enumerate(sizes):
            name = f'download {index} café.bin'
            relative = Path(name) / 'nested/first.bin' if index % 2 else Path(name)
            expected[relative] = payload(incoming / relative, size, index)
            if index % 2:
                extra = Path(name) / 'second.txt'
                expected[extra] = payload(incoming / extra, index * 11, index)
                (incoming / name / 'empty').mkdir()
            jobs.append((incoming / relative, 2 if index % 2 else 1))
        children = [launch(cfg, source, count, f'{label}-{index}')
                    for index, (source, count) in enumerate(jobs)]
        wait_all(children)
        for relative, expected_hash in expected.items():
            assert digest(completed / relative) == expected_hash, relative
        for index in (1, 3, 5, 7):
            assert (completed / f'download {index} café.bin' / 'empty').is_dir()
        assert not list(incoming.iterdir()), 'sources retained'
        assert len(list(completed.iterdir())) == len(jobs), 'staging or extra destinations'
        record('filesystem-pair', source=src_root.name, destination=dst_root.name,
               hooks=len(jobs), hashes='PASS', cleanup='PASS')


def paused_copy():
    with tempfile.TemporaryDirectory(dir=ROOTS[2]) as src, \
            tempfile.TemporaryDirectory(dir=ROOTS[3]) as dst:
        incoming, completed = Path(src), Path(dst)
        cfg = config(incoming, completed, 'paused-copy')
        large = incoming / 'large.bin'
        expected = payload(large, 128 * 1024**2, 9)
        small = [(incoming / f'small-{i}.bin', i) for i in range(8)]
        hashes = {path.name: payload(path, 65537 + i, i) for path, i in small}
        child = launch(cfg, large, 1, 'paused-large')
        paused = False
        try:
            deadline = time.monotonic() + 60
            while not paused:
                assert child.poll() is None, 'large hook finished before overlap was established'
                assert time.monotonic() < deadline, 'partial staging copy was not observed'
                for stage in completed.glob('.aria_move.stage.*/large.bin'):
                    try:
                        if 0 < stage.stat().st_size < large.stat().st_size:
                            os.kill(child.pid, signal.SIGSTOP)
                            paused = True
                            break
                    except FileNotFoundError:
                        pass
                time.sleep(.001)
            siblings = [launch(cfg, path, 1, f'paused-small-{i}') for path, i in small]
            wait_all(siblings)
            assert not (completed / large.name).exists()
            for name, expected_hash in hashes.items():
                assert digest(completed / name) == expected_hash
        finally:
            if paused:
                os.kill(child.pid, signal.SIGCONT)
            wait_all([child])
        assert digest(completed / large.name) == expected
        assert not list(incoming.iterdir())
        assert len(list(completed.iterdir())) == 9
        record('paused-large-copy', size_mib=128, siblings_finished_while_paused=8,
               hashes='PASS', cleanup='PASS')


class Handler(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *_):
        pass


def actual_aria2_hooks():
    with tempfile.TemporaryDirectory(dir=ROOTS[0]) as src, \
            tempfile.TemporaryDirectory(dir=ROOTS[3]) as dst, \
            tempfile.TemporaryDirectory() as web:
        incoming, completed = Path(src), Path(dst)
        cfg = config(incoming, completed, 'actual-aria2')
        hashes = {f'http-{i}.bin': payload(Path(web) / f'http-{i}.bin', 1048576 + i * 137, i)
                  for i in range(8)}
        server = http.server.ThreadingHTTPServer(('127.0.0.1', 0),
                    functools.partial(Handler, directory=web))
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        try:
            env = dict(os.environ, ARIA_MOVE_CONFIG=str(cfg))
            # Positional URLs are mirrors of one item in aria2. An input file
            # makes these eight independent downloads and completion hooks.
            urls = RESULTS / 'aria2-input.txt'
            urls.write_text(''.join(f'http://127.0.0.1:{server.server_port}/{name}\n'
                                    for name in hashes))
            with (RESULTS / 'aria2.log').open('wb') as output:
                subprocess.run(['aria2c', '--no-conf', '--max-concurrent-downloads=8',
                    '--split=1', '--file-allocation=none', '--auto-file-renaming=false',
                    '--on-download-complete=' + BIN, '--dir=' + str(incoming),
                    '--input-file=' + str(urls)],
                    env=env, stdout=output, stderr=subprocess.STDOUT, timeout=120, check=True)
            deadline = time.monotonic() + 90
            while list(incoming.iterdir()) or len(list(completed.iterdir())) != len(hashes):
                assert time.monotonic() < deadline, 'actual aria2 hooks did not finish'
                time.sleep(.05)
            for name, expected_hash in hashes.items():
                assert digest(completed / name) == expected_hash
        finally:
            server.shutdown()
            server.server_close()
            thread.join()
        record('actual-aria2-completion-hooks', downloads=8, hashes='PASS', cleanup='PASS')


def smb_timestamp_refresh():
    """A finished file keeps its bytes while metadata changes during copying."""
    with tempfile.TemporaryDirectory(dir=ROOTS[3]) as src, \
            tempfile.TemporaryDirectory(dir=ROOTS[1]) as dst:
        incoming, completed = Path(src), Path(dst)
        cfg = config(incoming, completed, 'smb-timestamp-refresh')
        source = incoming / 'finished.bin'
        expected = payload(source, 128 * 1024**2, 21)
        child = launch(cfg, source, 1, 'smb-timestamp-refresh')
        paused = False
        try:
            deadline = time.monotonic() + 60
            while not paused:
                assert child.poll() is None, 'copy finished before timestamp test overlap'
                assert time.monotonic() < deadline, 'timestamp test saw no partial copy'
                for staged in completed.glob('.aria_move.stage.*/finished.bin'):
                    try:
                        if 0 < staged.stat().st_size < source.stat().st_size:
                            os.kill(child.pid, signal.SIGSTOP)
                            os.waitpid(child.pid, os.WUNTRACED)
                            paused = True
                            break
                    except FileNotFoundError:
                        pass
                time.sleep(.001)
            assert not (completed / source.name).exists()
            meta = source.stat()
            os.utime(source, ns=(meta.st_atime_ns, meta.st_mtime_ns + 2_000_000_000))
        finally:
            if paused:
                os.kill(child.pid, signal.SIGCONT)
            wait_all([child], seconds=180)
        assert digest(completed / source.name) == expected
        assert not list(incoming.iterdir())
        assert len(list(completed.iterdir())) == 1
        log = (RESULTS / 'smb-timestamp-refresh.log').read_text()
        assert 'retrying verified copy before publication' in log, log
        record('smb-timestamp-refresh', finished_file_bytes_unchanged=True,
               retry_observed=True, hashes='PASS', cleanup='PASS')


record('environment', debian=Path('/etc/debian_version').read_text().strip(),
       kernel=os.uname().release, filesystems=[p.name for p in ROOTS])
for src, dst in itertools.product(ROOTS, repeat=2):
    batch(src, dst)
paused_copy()
smb_timestamp_refresh()
actual_aria2_hooks()
record('complete', status='PASS')
